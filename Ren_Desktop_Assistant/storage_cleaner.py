"""
Advanced Storage Cleaner & Verification Engine for REN-AI Windows Control Center
Provides:
- Itemized scanning of Windows junk, temp files, shader caches, crash dumps, and Recycle Bin.
- Zero-destruction preview before any deletion occurs.
- Safe cleaning: handles file locks gracefully without crashing.
- Verification pass: confirms actual megabytes reclaimed.
"""

import os
